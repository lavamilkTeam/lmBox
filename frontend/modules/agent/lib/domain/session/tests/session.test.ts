import { beforeEach, describe, expect, it } from 'vitest'
import { createPinia, setActivePinia } from 'pinia'
import type { AiJob, AiRequest, AiResponse } from '../../../../../../contracts'
import { useAgentSession } from '../index'
function response(request: AiRequest, job: AiJob): AiResponse { return { schemaVersion: 1, projectId: request.projectId, requestId: request.requestId, inputRevision: request.inputRevision, capability: 'agent', ok: true, data: { job } } }
function job(request: AiRequest, status: AiJob['status'] = 'running'): AiJob { return { jobId: 'agent-job', capability: 'agent', inputRevision: request.inputRevision, status, events: [{ message: 'working' }] } }
describe('agent session public domain', () => {
  beforeEach(() => setActivePinia(createPinia()))
  it('snapshots task inputs and blocks edits until the task ends', () => {
    const session = useAgentSession(); session.initialize('agent-test')
    expect(session.validate()).toContain('请输入')
    session.setPrompt('Summarize the attachment'); session.setMaxSteps(4)
    expect(session.addFiles([{ name: 'notes.txt', content: 'One\nTwo' }])).toBe('')
    const start = session.request('start')
    expect(start.payload).toEqual({ prompt: 'Summarize the attachment', maxSteps: 4, files: [{ name: 'notes.txt', content: 'One\nTwo' }] })
    session.setPrompt('new'); session.setMaxSteps(12); session.removeFile(0)
    expect(session.prompt).toBe('Summarize the attachment'); expect(session.maxSteps).toBe(4); expect(session.files).toHaveLength(1)
    expect(session.accept(start, response(start, job(start)))).toBe(true)
    expect(session.prompt).toBe(''); expect(session.files).toEqual([])
    const poll = session.request('status')
    expect(session.accept(poll, response(poll, { ...job(start, 'succeeded'), result: { text: 'Two lines', artifacts: [] } }))).toBe(true)
    expect(session.job?.result?.text).toBe('Two lines')
    session.setPrompt('Another task')
    expect(session.job?.result?.text).toBe('Two lines'); expect(session.revision).toBeGreaterThan(start.inputRevision)
    expect(session.turns).toMatchObject([{ prompt: 'Summarize the attachment', files: [{ name: 'notes.txt', size: 7 }], job: { result: { text: 'Two lines' } } }])
  })
  it('rejects duplicate or out-of-scope file names without partially adding files', () => {
    const session = useAgentSession()
    expect(session.addFiles([{ name: 'a.txt', content: 'a' }])).toBe('')
    expect(session.addFiles([{ name: 'b.txt', content: 'b' }, { name: 'a.txt', content: 'duplicate' }])).toContain('同名')
    expect(session.files.map(file => file.name)).toEqual(['a.txt'])
    expect(session.addFiles([{ name: '../private.txt', content: 'x' }])).toContain('无效')
    expect(session.addFiles([{ name: 'huge.txt', content: '字'.repeat(350000) }])).toContain('超过')
    expect(session.files).toHaveLength(1)
  })
  it('enforces UTF-8 attachment totals across additions and the 32-step budget', () => {
    const session = useAgentSession(); session.setPrompt('Work')
    expect(session.addFiles([{ name: 'a.txt', content: '字'.repeat(200000) }])).toBe('')
    expect(session.addFiles([{ name: 'b.txt', content: '字'.repeat(160000) }])).toContain('1 MB')
    session.setMaxSteps(32); expect(session.validate()).toBe('')
    session.setMaxSteps(33); expect(session.validate()).toContain('1 至 32')
    session.setMaxSteps(1.5); expect(session.validate()).toContain('1 至 32')
  })
  it('recovers an uncertain start only by replaying its original identity and snapshot', () => {
    const session = useAgentSession(); session.initialize('project', 'request-session'); session.setPrompt('Work')
    const start = session.request('start'); session.fail(start, 'Response lost')
    expect(session.pending).toBe(false); expect(session.unconfirmed).toBe(true); expect(session.locked).toBe(true)
    session.setPrompt('Do something else')
    expect(session.prompt).toBe('Work')
    const retry = session.request('start')
    expect(retry).toEqual(start)
    expect(session.turns).toHaveLength(1)
    session.accept(retry, response(retry, job(retry)))
    expect(session.unconfirmed).toBe(false); expect(session.job?.jobId).toBe('agent-job')
  })
  it('unlocks editable input when the platform proves the start was never sent', () => {
    const session = useAgentSession(); session.initialize('project'); session.setPrompt('Original')
    const rejected = session.request('start'); session.fail(rejected, 'Request too large', true)
    expect(session.pending).toBe(false); expect(session.unconfirmed).toBe(false); expect(session.locked).toBe(false)
    session.setPrompt('Smaller task')
    const retry = session.request('start')
    expect(retry.requestId).not.toBe(rejected.requestId)
    expect(retry.payload?.prompt).toBe('Smaller task')
    expect(session.turns).toMatchObject([{ prompt: 'Original', submission: 'failed' }, { prompt: 'Smaller task', submission: 'submitting' }])
  })
  it('accepts portable Unicode names and rejects names that the Python workspace cannot stage', () => {
    const session = useAgentSession()
    for (const name of ['notes(1).txt', '.env', 'a..txt', 'a.txt ', 'a.', '-draft.txt', 'x'.repeat(129)]) expect(session.addFiles([{ name, content: '' }])).toContain('无效')
    expect(session.files).toEqual([])
    expect(session.addFiles([{ name: '分析 1-2.txt', content: '' }, { name: '_notes.txt', content: '' }])).toBe('')
  })
  it('does not turn a cancellation request into a cancelled result', () => {
    const session = useAgentSession(); session.initialize('agent-test'); session.setPrompt('Work')
    const start = session.request('start'); session.accept(start, response(start, job(start)))
    const oldPoll = session.request('status'), cancel = session.request('cancel')
    session.accept(cancel, response(cancel, { ...job(start), events: [{ message: 'Cancellation requested' }] }))
    expect(session.job?.status).toBe('running'); expect(session.locked).toBe(true)
    expect(session.accept(oldPoll, response(oldPoll, job(start, 'succeeded')))).toBe(false)
    const freshPoll = session.request('status'); session.accept(freshPoll, response(freshPoll, job(start, 'cancelled')))
    expect(session.job?.status).toBe('cancelled'); expect(session.locked).toBe(false)
  })
  it('rejects mismatched identity and retains a running job across failed status calls', () => {
    const session = useAgentSession(); session.initialize('agent-test'); session.setPrompt('Work')
    const start = session.request('start')
    expect(session.accept(start, { ...response(start, job(start)), projectId: 'different' })).toBe(false)
    expect(session.accept(start, response(start, job(start)))).toBe(true)
    const poll = session.request('status'); session.fail(poll, 'offline')
    expect(session.locked).toBe(true)
    expect(session.accept(poll, response(poll, { ...job(start), inputRevision: start.inputRevision + 1 }))).toBe(false)
    expect(session.job?.inputRevision).toBe(start.inputRevision)
    const fresh = session.request('status'); session.accept(fresh, response(fresh, job(start, 'failed')))
    expect(session.locked).toBe(false)
  })
  it('uses the last successful job as trusted context and preserves earlier outputs', () => {
    const session = useAgentSession(); session.initialize('conversation'); session.setPrompt('First turn')
    session.addFiles([{ name: 'input.txt', content: 'source' }])
    const first = session.request('start')
    session.accept(first, response(first, { ...job(first, 'succeeded'), jobId: 'first-job', result: { text: 'First answer', artifacts: [{ id: 'result.txt', name: 'result.txt', mimeType: 'text/plain' }] } }))
    session.setPrompt('Follow up')
    const second = session.request('start')
    expect(second.payload).toEqual({ prompt: 'Follow up', maxSteps: 8, files: [], parentJobId: 'first-job' })
    expect(session.turns[0].job?.result?.text).toBe('First answer')
    session.fail(second, 'Response lost')
    const recovered = session.request('start')
    expect(recovered).toEqual(second); expect(session.turns).toHaveLength(2)
    session.accept(second, response(second, { ...job(second, 'cancelled'), jobId: 'second-job' }))
    session.setPrompt('Another follow up')
    const third = session.request('start')
    expect(third.payload?.parentJobId).toBe('first-job')
    expect(session.turns).toHaveLength(3)
  })
  it('retrieves historical artifacts with their own revision without superseding a live poll', () => {
    const session = useAgentSession(); session.initialize('conversation'); session.setPrompt('Create a file')
    const first = session.request('start')
    session.accept(first, response(first, { ...job(first, 'succeeded'), jobId: 'first-job', result: { text: 'Saved', artifacts: [{ id: 'result.txt', name: 'result.txt', mimeType: 'text/plain' }] } }))
    session.setPrompt('Continue')
    const second = session.request('start')
    expect(session.accept(first, response(first, job(first)))).toBe(false)
    session.accept(second, response(second, { ...job(second), jobId: 'second-job' }))
    const poll = session.request('status'), download = session.artifactRequest(first.requestId, 'result.txt')!
    expect(download).toMatchObject({ projectId: 'conversation', jobId: 'first-job', inputRevision: first.inputRevision, operation: 'artifact', payload: { artifactId: 'result.txt' } })
    expect(download.requestId).not.toBe(poll.requestId)
    expect(session.artifactRequest(first.requestId, 'unknown.txt')).toBeUndefined()
    expect(session.accept(poll, response(poll, { ...job(second, 'succeeded'), jobId: 'second-job', result: { text: 'Done', artifacts: [] } }))).toBe(true)
    expect(session.answer(first.requestId)).toBe('Saved')
    expect(session.answer(second.requestId)).toBe('Done')
  })
  it('cannot reset a running conversation and rejects old replies after starting a new conversation', () => {
    const session = useAgentSession(); session.initialize('conversation'); session.setPrompt('Work')
    const first = session.request('start')
    session.newConversation(); expect(session.turns).toHaveLength(1)
    session.accept(first, response(first, job(first)))
    session.newConversation(); expect(session.turns).toHaveLength(1)
    const poll = session.request('status')
    session.accept(poll, response(poll, { ...job(first, 'succeeded'), result: { text: 'Done', artifacts: [] } }))
    session.setPrompt('Draft'); session.addFiles([{ name: 'draft.txt', content: 'draft' }])
    session.newConversation()
    expect(session.turns).toEqual([]); expect(session.prompt).toBe(''); expect(session.files).toEqual([])
    expect(session.accept(poll, response(poll, job(first)))).toBe(false)
    session.setPrompt('Fresh start')
    expect(session.request('start').payload).not.toHaveProperty('parentJobId')
  })
  it('does not duplicate completed turns or regress them from late running snapshots', () => {
    const session = useAgentSession(); session.initialize('conversation'); session.setPrompt('Work')
    const start = session.request('start'), done = { ...job(start, 'succeeded'), result: { text: 'Done', artifacts: [] } }
    session.accept(start, response(start, done))
    session.setPrompt('Draft next turn')
    session.accept(start, response(start, done))
    expect(session.prompt).toBe('Draft next turn')
    expect(session.turns).toHaveLength(1)
    expect(session.accept(start, response(start, job(start)))).toBe(false)
    expect(session.job?.status).toBe('succeeded')
  })
  it('bounds conversations to twenty completed turns without silently dropping context', () => {
    const session = useAgentSession(); session.initialize('conversation')
    for (let index = 0; index < 20; index++) {
      session.setPrompt(`Turn ${index}`); expect(session.validate()).toBe('')
      const request = session.request('start')
      session.accept(request, response(request, { ...job(request, 'succeeded'), jobId: `job-${index}`, result: { text: `Answer ${index}`, artifacts: [] } }))
    }
    session.setPrompt('One more turn')
    expect(session.validate()).toContain('20 轮')
    expect(session.completedCount).toBe(20); expect(session.turns).toHaveLength(20)
    session.newConversation(); session.setPrompt('New conversation')
    expect(session.validate()).toBe('')
  })
})

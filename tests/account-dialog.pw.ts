import { openWorkbench } from './workspace-navigation'
import { test, expect } from '@playwright/test'

test('account dialog validates registration and never treats an unavailable account service as success', async ({ page }) => {
  const transmittedCredentials: string[] = []
  page.on('request', request => {
    if (request.postData()?.includes('dialog-test@example.com')) transmittedCredentials.push(request.url())
  })
  await openWorkbench(page)
  await page.getByRole('button', { name: '请登陆', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '账户', exact: true })
  for (const provider of ['微信', 'QQ', 'GitHub']) {
    const providerButton = dialog.getByRole('button', { name: `${provider} 登录`, exact: true })
    await expect.poll(() => providerButton.locator('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
    await providerButton.click()
    await expect(dialog.getByRole('alert')).toHaveText(`${provider} 授权服务尚未接入，暂时无法登录。`)
  }
  await dialog.getByLabel('邮箱', { exact: true }).fill('dialog-test@example.com')
  await dialog.getByLabel('密码', { exact: true }).fill('test-only-password')
  await dialog.getByRole('tab', { name: '注册', exact: true }).click()
  await expect(dialog.getByLabel('邮箱', { exact: true })).toHaveValue('dialog-test@example.com')
  await expect(dialog.getByLabel('密码', { exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: '获取验证码', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('邮箱验证码服务尚未接入，暂时无法发送。')
  for (const provider of ['微信', 'QQ', 'GitHub']) {
    await dialog.getByRole('button', { name: `绑定 ${provider}`, exact: true }).click()
    await expect(dialog.getByRole('alert')).toHaveText(`${provider} 授权服务尚未接入，暂时无法绑定。`)
  }
  await dialog.getByLabel('邮箱验证码', { exact: true }).fill('test-code')
  await dialog.getByLabel('密码', { exact: true }).fill('test-only-password')
  await dialog.getByLabel('确认密码', { exact: true }).fill('different-test-password')
  await dialog.getByRole('button', { name: '注册', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('两次输入的密码不一致。')
  await expect(dialog.getByLabel('确认密码', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await dialog.getByLabel('确认密码', { exact: true }).fill('test-only-password')
  await dialog.getByRole('button', { name: '注册', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('统一账户服务尚未接入，暂时无法注册。')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('tab', { name: '登录', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveCount(0)
  await expect(dialog.getByLabel('密码', { exact: true })).toHaveValue('')
  await dialog.getByLabel('密码', { exact: true }).fill('test-only-password')
  await dialog.getByRole('button', { name: '登录', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('统一账户服务尚未接入，暂时无法登录。')
  expect(transmittedCredentials).toEqual([])
})

test('account dialog fits a narrow viewport, clears closed drafts and returns keyboard focus', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 640 })
  await openWorkbench(page)
  const trigger = page.getByRole('button', { name: '请登陆', exact: true })
  await trigger.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: '账户', exact: true })
  await dialog.getByRole('tab', { name: '注册', exact: true }).click()
  await dialog.getByLabel('邮箱', { exact: true }).fill('dialog-test@example.com')
  await dialog.getByLabel('密码', { exact: true }).fill('test-only-password')
  await dialog.getByLabel('确认密码', { exact: true }).fill('test-only-password')
  await dialog.getByLabel('邮箱验证码', { exact: true }).fill('test-code')
  const bindings = await dialog.getByRole('group', { name: '绑定账号（可选）' }).boundingBox()
  const register = await dialog.getByRole('button', { name: '注册', exact: true }).boundingBox()
  expect(bindings).not.toBeNull()
  expect(register).not.toBeNull()
  expect(bindings!.y + bindings!.height).toBeLessThanOrEqual(register!.y)
  const bounds = await dialog.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(360)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(640)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dialog.getByLabel('邮箱', { exact: true })).toHaveValue('')
  await expect(dialog.getByLabel('密码', { exact: true })).toHaveValue('')
  await expect(dialog.getByLabel('确认密码', { exact: true })).toHaveValue('')
  await expect(dialog.getByLabel('邮箱验证码', { exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

import { expect, test } from '@playwright/test'
import { openWorkbench, selectWorkspace } from './workspace-navigation'
import { aiRuntimeFixture } from './ai-runtime-fixture'

test('chat history preserves drafts and files, searches titles and survives workspace changes', async ({ page }) => {
  await openWorkbench(page)
  await selectWorkspace(page, 'Agent')
  const history = page.getByRole('complementary', { name: '聊天记录', exact: true })
  const prompt = page.getByLabel('Agent 任务', { exact: true })
  await expect(history).toBeVisible()
  await prompt.fill('First project draft')
  await page.getByLabel('选择 Agent 文本文件', { exact: true }).setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('a draft attachment') })
  await expect(page.getByLabel('待发送附件')).toContainText('notes.txt')
  await history.getByRole('button', { name: '新建聊天', exact: true }).click()
  await expect(prompt).toHaveValue('')
  await expect(page.getByLabel('待发送附件')).toHaveCount(0)
  await prompt.fill('Second project draft')
  await history.getByLabel('搜索聊天记录').fill('first')
  await expect(history.getByRole('button', { name: 'Second project draft', exact: true })).toHaveCount(0)
  await history.getByRole('button', { name: 'First project draft', exact: true }).click()
  await expect(prompt).toHaveValue('First project draft')
  await expect(page.getByLabel('待发送附件')).toContainText('notes.txt')
  await history.getByLabel('搜索聊天记录').fill('')
  await selectWorkspace(page, '引导界面')
  await expect(prompt).toHaveValue('First project draft')
  await selectWorkspace(page, 'Agent')
  await history.getByRole('button', { name: 'Second project draft', exact: true }).click()
  await expect(prompt).toHaveValue('Second project draft')
  await history.getByRole('button', { name: '收起聊天记录', exact: true }).click()
  await expect(history).toBeHidden()
  await page.getByRole('button', { name: '展开聊天记录', exact: true }).click()
  await expect(history).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(prompt).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('saved chats keep real task history and downloads and continue only their own conversation', async ({ page }) => {
  const runtime = await aiRuntimeFixture(page)
  try {
    await openWorkbench(page)
    await selectWorkspace(page, 'Agent')
    const history = page.getByRole('complementary', { name: '聊天记录', exact: true })
    const prompt = page.getByLabel('Agent 任务', { exact: true })
    await page.getByRole('button', { name: '选择模型', exact: true }).click()
    await page.getByRole('dialog', { name: '选择模型', exact: true }).getByRole('button', { name: '对话设置', exact: true }).click()
    await expect(page.getByText('fixture-agent-model', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '关闭对话设置', exact: true }).click()
    await prompt.fill('Fixture: write 42')
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await expect(page.getByLabel('助手回复 1', { exact: true })).toContainText('answer.txt contains 42', { timeout: 20000 })
    await history.getByRole('button', { name: '新建聊天', exact: true }).click()
    await prompt.fill('Fixture new conversation')
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await expect(page.getByLabel('助手回复 1', { exact: true })).toContainText('answer.txt contains 42', { timeout: 20000 })
    await history.getByRole('button', { name: 'Fixture: write 42', exact: true }).click()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载 answer.txt', exact: true }).click()
    expect((await download).suggestedFilename()).toBe('answer.txt')
    await prompt.fill('Fixture follow-up')
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await expect(page.getByLabel('助手回复 2', { exact: true })).toContainText('previous answer was 42', { timeout: 20000 })
    expect(runtime.counts().completions).toBe(5)
  } finally { await runtime.close() }
})

test('running chats cannot be switched until cancellation finishes', async ({ page }) => {
  const runtime = await aiRuntimeFixture(page)
  runtime.slowAgent()
  try {
    await openWorkbench(page)
    await selectWorkspace(page, 'Agent')
    const history = page.getByRole('complementary', { name: '聊天记录', exact: true })
    const prompt = page.getByLabel('Agent 任务', { exact: true })
    await prompt.fill('Earlier draft')
    await history.getByRole('button', { name: '新建聊天', exact: true }).click()
    await page.getByRole('button', { name: '选择模型', exact: true }).click()
    await page.getByRole('dialog', { name: '选择模型', exact: true }).getByRole('button', { name: '对话设置', exact: true }).click()
    await expect(page.getByText('fixture-agent-model', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '关闭对话设置', exact: true }).click()
    await prompt.fill('Running task')
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await expect.poll(() => runtime.counts().completions).toBe(1)
    await expect(history.getByRole('button', { name: 'Earlier draft', exact: true })).toBeDisabled()
    await expect(history.getByRole('button', { name: '新建聊天', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '取消任务', exact: true }).click()
    await expect(history.getByRole('button', { name: 'Earlier draft', exact: true })).toBeEnabled({ timeout: 15000 })
    await history.getByRole('button', { name: 'Earlier draft', exact: true }).click()
    await expect(prompt).toHaveValue('Earlier draft')
  } finally { await runtime.close() }
})

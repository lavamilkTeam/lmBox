import { expect, test, type Locator, type Page } from '@playwright/test'
import { selectWorkspace, openWorkbench } from './workspace-navigation'

function node(page: Page, label: string) { return page.getByRole('article', { name: label, exact: true }) }
function reading(page: Page, label: string, probe = false) {
  return node(page, label).getByRole('status', { name: `${label}${probe ? '检测电平' : '输出电平'}`, exact: true })
}
function wire(page: Page, source: string, target: string, port: string) {
  return page.getByRole('button', { name: `连接：${source} → ${target} ${port}`, exact: true })
}
function visibleWire(hitArea: Locator) { return hitArea.locator('..').locator('path').first() }
const highStroke = 'rgb(38, 120, 71)'
async function add(page: Page, label: string, position?: { x: number; y: number }) {
  const button = page.getByRole('button', { name: `添加${label}`, exact: true })
  if (position) await button.dragTo(page.getByLabel('逻辑电路画布', { exact: true }), { targetPosition: position })
  else await button.click()
  await expect(node(page, label)).toBeVisible()
}
async function connect(page: Page, source: string, target: string, port: string) {
  await node(page, source).getByRole('button', { name: `${source}输出端`, exact: true }).click()
  await node(page, target).getByRole('button', { name: `${target}输入端 ${port}`, exact: true }).click()
  await expect(page.getByRole('button', { name: `连接：${source} → ${target} ${port}`, exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: '单步仿真', exact: true })).toBeEnabled()
}
async function step(page: Page, tick: number) {
  await page.getByRole('button', { name: '单步仿真', exact: true }).click()
  await expect(page.getByRole('status', { name: '仿真步数', exact: true })).toHaveText(`t = ${tick}`)
}
async function drag(page: Page, handle: Locator, dx: number, dy: number) {
  const bounds = (await handle.boundingBox())!
  const x = bounds.x + bounds.width / 2, y = bounds.y + bounds.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + dx, y + dy, { steps: 6 })
  await page.mouse.up()
}

test('real Rust worker propagates inputs, colors wires and preserves state across movement and tabs until topology changes', async ({ page }, testInfo) => {
  const workers: string[] = [], errors: string[] = []
  page.on('worker', worker => workers.push(worker.url()))
  page.on('pageerror', error => errors.push(error.message))
  await openWorkbench(page)
  await selectWorkspace(page, '数字逻辑仿真')
  const canvas = page.getByLabel('逻辑电路画布', { exact: true })
  const initialCanvas = (await canvas.boundingBox())!
  await add(page, '输入开关')
  await add(page, '非门 NOT', { x: 400, y: 110 })
  await add(page, '电平探针', { x: 680, y: 110 })
  await expect(reading(page, '输入开关')).toHaveText('0')
  await expect(reading(page, '非门 NOT')).toHaveText('X')
  await expect(reading(page, '电平探针', true)).toHaveText('Z')
  expect((await canvas.boundingBox())!.y).toBe(initialCanvas.y)
  const diagnostics = page.getByRole('button', { name: '仿真诊断', exact: true })
  await diagnostics.click()
  await expect(page.getByRole('dialog', { name: '仿真诊断', exact: true })).toBeVisible()
  expect((await canvas.boundingBox())!.y).toBe(initialCanvas.y)
  await page.keyboard.press('Escape')
  await expect(diagnostics).toBeFocused()
  const toggle = node(page, '输入开关').getByRole('button', { name: '切换输入开关电平', exact: true })
  await expect(toggle).toHaveText('0')
  await connect(page, '输入开关', '非门 NOT', 'A')
  await connect(page, '非门 NOT', '电平探针', 'A')
  await expect(reading(page, '非门 NOT')).toHaveText('1')
  await expect(reading(page, '电平探针', true)).toHaveText('1')
  const inputWire = visibleWire(wire(page, '输入开关', '非门 NOT', 'A'))
  const invertedWire = visibleWire(wire(page, '非门 NOT', '电平探针', 'A'))
  const normalStroke = await inputWire.evaluate(element => getComputedStyle(element).stroke)
  expect(normalStroke).not.toBe(highStroke)
  await expect(invertedWire).toHaveCSS('stroke', highStroke)
  await expect(diagnostics).toHaveText('诊断 0')
  expect((await canvas.boundingBox())!.y).toBe(initialCanvas.y)
  await toggle.click()
  await expect(toggle).toHaveText('1')
  await expect(reading(page, '输入开关')).toHaveText('1')
  await expect(reading(page, '非门 NOT')).toHaveText('0')
  await expect(reading(page, '电平探针', true)).toHaveText('0')
  await expect(inputWire).toHaveCSS('stroke', highStroke)
  await expect(invertedWire).toHaveCSS('stroke', normalStroke)
  await step(page, 1)
  await step(page, 2)

  const handle = node(page, '非门 NOT').getByRole('button', { name: '移动非门 NOT', exact: true })
  const before = (await handle.boundingBox())!
  await drag(page, handle, 40, 30)
  const after = (await handle.boundingBox())!
  expect(after.x - before.x).toBeCloseTo(40, 0)
  expect(after.y - before.y).toBeCloseTo(30, 0)
  await expect(page.getByRole('status', { name: '仿真步数', exact: true })).toHaveText('t = 2')
  await selectWorkspace(page, '引导界面')
  await selectWorkspace(page, '数字逻辑仿真')
  await expect(page.getByRole('status', { name: '仿真步数', exact: true })).toHaveText('t = 2')
  await expect(toggle).toHaveText('1')
  await expect(reading(page, '电平探针', true)).toHaveText('0')
  await expect(inputWire).toHaveCSS('stroke', highStroke)
  await expect(invertedWire).toHaveCSS('stroke', normalStroke)
  await add(page, '缓冲器 BUF')
  await expect(page.getByRole('status', { name: '仿真步数', exact: true })).toHaveText('t = 0')
  await expect(reading(page, '输入开关')).toHaveText('1')
  await expect(reading(page, '电平探针', true)).toHaveText('0')
  await connect(page, '输入开关', '缓冲器 BUF', 'A')
  const branch = wire(page, '输入开关', '缓冲器 BUF', 'A')
  const branchWire = visibleWire(branch)
  await expect(reading(page, '缓冲器 BUF')).toHaveText('1')
  await expect(inputWire).toHaveCSS('stroke', highStroke)
  await expect(branchWire).toHaveCSS('stroke', highStroke)

  await toggle.click()
  await expect(reading(page, '输入开关')).toHaveText('0')
  await expect(reading(page, '缓冲器 BUF')).toHaveText('0')
  await expect(reading(page, '电平探针', true)).toHaveText('1')
  await expect(inputWire).toHaveCSS('stroke', normalStroke)
  await expect(branchWire).toHaveCSS('stroke', normalStroke)
  await expect(invertedWire).toHaveCSS('stroke', highStroke)
  await toggle.click()
  await expect(reading(page, '输入开关')).toHaveText('1')
  await expect(reading(page, '缓冲器 BUF')).toHaveText('1')
  await expect(inputWire).toHaveCSS('stroke', highStroke)
  await expect(branchWire).toHaveCSS('stroke', highStroke)
  await expect(invertedWire).toHaveCSS('stroke', normalStroke)

  const unfocusedHitStroke = await branch.evaluate(element => getComputedStyle(element).stroke)
  await branch.focus()
  await branch.press('Enter')
  await expect(branch).toBeFocused()
  await expect(branch).toHaveAttribute('aria-pressed', 'true')
  await expect(branchWire).toHaveCSS('stroke', highStroke)
  await expect(branchWire).toHaveCSS('stroke-width', '3px')
  await expect(branch).not.toHaveCSS('stroke', unfocusedHitStroke)
  const screenshot = testInfo.outputPath('digital-logic-high-wires.png')
  await page.screenshot({ path: screenshot })
  await testInfo.attach('High output colors both branches while the selected wire remains green', { path: screenshot, contentType: 'image/png' })
  await branch.press('Delete')
  await expect(branch).toHaveCount(0)
  await expect(reading(page, '缓冲器 BUF')).toHaveText('X')
  await expect(inputWire).toHaveCSS('stroke', highStroke)
  expect(workers.some(url => url.includes('digital-logic.worker'))).toBe(true)
  expect(errors).toEqual([])
})

test('clock-driven D flip-flop samples rising edges and run, pause and reset use real simulation state', async ({ page }) => {
  await openWorkbench(page)
  await selectWorkspace(page, '数字逻辑仿真')
  await add(page, '输入开关')
  await add(page, '时钟', { x: 150, y: 300 })
  await add(page, 'D 触发器', { x: 440, y: 180 })
  await add(page, '电平探针', { x: 740, y: 180 })
  await connect(page, '输入开关', 'D 触发器', 'D')
  await connect(page, '时钟', 'D 触发器', 'CLK')
  await connect(page, 'D 触发器', '电平探针', 'A')
  const toggle = node(page, '输入开关').getByRole('button', { name: '切换输入开关电平', exact: true })
  await expect(reading(page, '时钟')).toHaveText('0')
  await expect(reading(page, 'D 触发器')).toHaveText('X')
  await expect(reading(page, '电平探针', true)).toHaveText('X')
  const clockWire = visibleWire(wire(page, '时钟', 'D 触发器', 'CLK'))
  const outputWire = visibleWire(wire(page, 'D 触发器', '电平探针', 'A'))
  const normalStroke = await clockWire.evaluate(element => getComputedStyle(element).stroke)
  await expect(outputWire).toHaveCSS('stroke', normalStroke)
  await toggle.click()
  await expect(reading(page, '输入开关')).toHaveText('1')
  await expect(reading(page, 'D 触发器')).toHaveText('X')
  await step(page, 1)
  await expect(reading(page, '时钟')).toHaveText('1')
  await expect(reading(page, 'D 触发器')).toHaveText('1')
  await expect(reading(page, '电平探针', true)).toHaveText('1')
  await expect(clockWire).toHaveCSS('stroke', highStroke)
  await expect(outputWire).toHaveCSS('stroke', highStroke)
  await toggle.click()
  await expect(reading(page, '输入开关')).toHaveText('0')
  await expect(reading(page, 'D 触发器')).toHaveText('1')
  await step(page, 2)
  await expect(reading(page, '时钟')).toHaveText('0')
  await expect(reading(page, 'D 触发器')).toHaveText('1')
  await expect(clockWire).toHaveCSS('stroke', normalStroke)
  await expect(outputWire).toHaveCSS('stroke', highStroke)
  await step(page, 3)
  await expect(reading(page, '时钟')).toHaveText('1')
  await expect(reading(page, 'D 触发器')).toHaveText('0')
  await expect(reading(page, '电平探针', true)).toHaveText('0')

  await page.getByRole('button', { name: '运行仿真', exact: true }).click()
  const tick = page.getByRole('status', { name: '仿真步数', exact: true })
  await expect.poll(async () => Number((await tick.innerText()).replace('t = ', ''))).toBeGreaterThan(3)
  await page.getByRole('button', { name: '暂停仿真', exact: true }).click()
  await expect(page.getByRole('button', { name: '单步仿真', exact: true })).toBeEnabled()
  const pausedTick = await tick.innerText()
  await selectWorkspace(page, '引导界面')
  await selectWorkspace(page, '数字逻辑仿真')
  await expect(page.getByRole('button', { name: '运行仿真', exact: true })).toBeVisible()
  await expect(tick).toHaveText(pausedTick)
  await expect(reading(page, 'D 触发器')).toHaveText('0')
  await add(page, '缓冲器 BUF')
  await expect(tick).toHaveText('t = 0')
  await expect(reading(page, '时钟')).toHaveText('0')
  await expect(reading(page, 'D 触发器')).toHaveText('X')
  await step(page, 1)
  await expect(reading(page, 'D 触发器')).toHaveText('0')
  await page.getByRole('button', { name: '复位仿真', exact: true }).click()
  await expect(tick).toHaveText('t = 0')
  await expect(reading(page, '时钟')).toHaveText('0')
  await expect(reading(page, 'D 触发器')).toHaveText('X')
  await expect(reading(page, '电平探针', true)).toHaveText('X')
  await expect(clockWire).toHaveCSS('stroke', normalStroke)
  await expect(outputWire).toHaveCSS('stroke', normalStroke)
})

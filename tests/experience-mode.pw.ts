import { test, expect } from '@playwright/test'
import { openWorkbench, selectWorkspace } from './workspace-navigation'

test('guest chooses an Agent-only layout and can return to the workbench without losing the Agent draft', async ({ page }) => {
  await page.goto('/')
  const dialog = page.getByRole('dialog', { name: '选择使用方式' })
  await expect(dialog).toBeVisible()
  const easy = dialog.getByRole('button', { name: '轻松模式', exact: true })
  const advanced = dialog.getByRole('button', { name: '专业模式', exact: true })
  const left = await easy.boundingBox(), right = await advanced.boundingBox()
  expect(left!.x + left!.width).toBeLessThan(right!.x)
  await expect(easy).toBeEnabled()
  await easy.focus()
  await easy.press('Enter')
  await expect(dialog).toBeHidden()
  const tabs = page.getByRole('tablist', { name: '工作区页签' })
  await expect(tabs).toBeVisible()
  await expect(tabs.getByRole('tab', { name: 'Agent', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('complementary', { name: 'AI 侧栏', exact: true })).toHaveCount(0)
  const prompt = page.getByLabel('Agent 任务', { exact: true })
  await prompt.fill('A local draft; do not send to a model')
  await page.getByRole('button', { name: '切换模式', exact: true }).click()
  await advanced.click()
  await expect(page.getByRole('tablist', { name: '工作区页签' })).toBeVisible()
  await expect(prompt).toHaveValue('A local draft; do not send to a model')
  await page.getByRole('tab', { name: '功能库', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: '切换模式', exact: true }).click()
  await easy.click()
  await expect(prompt).toHaveValue('A local draft; do not send to a model')
  await page.getByRole('button', { name: '切换模式', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: '切换模式', exact: true })).toBeFocused()
})

test('light mode retains opened tabs, restores the previous workspace and supports tab selection and closing', async ({ page }) => {
  await openWorkbench(page)
  await selectWorkspace(page, '数字逻辑仿真')
  const tabs = page.getByRole('tablist', { name: '工作区页签' })
  const logic = tabs.getByRole('tab', { name: '数字逻辑仿真', exact: true })
  const agent = tabs.getByRole('tab', { name: 'Agent', exact: true })
  const switchMode = page.getByRole('button', { name: '切换模式', exact: true })
  const dialog = page.getByRole('dialog', { name: '选择使用方式' })
  await switchMode.click()
  await dialog.getByRole('button', { name: '轻松模式', exact: true }).click()
  await expect(logic).toBeVisible()
  await expect(agent).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: '请登陆', exact: true })).toBeVisible()
  await switchMode.click()
  await dialog.getByRole('button', { name: '专业模式', exact: true }).click()
  await expect(logic).toHaveAttribute('aria-selected', 'true')
  await switchMode.click()
  await dialog.getByRole('button', { name: '轻松模式', exact: true }).click()
  await logic.click()
  await expect(logic).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('complementary', { name: 'AI 侧栏', exact: true })).toBeVisible()
  await switchMode.click()
  await dialog.getByRole('button', { name: '轻松模式', exact: true }).click()
  await tabs.getByRole('button', { name: '关闭Agent页签', exact: true }).click()
  await expect(agent).toHaveCount(0)
  await expect(logic).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('complementary', { name: 'AI 侧栏', exact: true })).toBeVisible()
})

test('compact guest selection fits the viewport and dismissal keeps the workbench usable', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 640 })
  await page.goto('/')
  const dialog = page.getByRole('dialog', { name: '选择使用方式' })
  await expect(dialog).toBeVisible()
  const bounds = (await dialog.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(360)
  expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(640)
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('tab', { name: '功能库', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: '切换模式', exact: true }).click()
  await expect(dialog).toBeVisible()
})

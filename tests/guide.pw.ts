import { test, expect } from '@playwright/test'
import { selectWorkspace } from './workspace-navigation'

test('startup hides unreleased injector; drag, zoom, move, connect and remove operate on the same graph', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('region', { name: '引导界面', exact: true })).toBeVisible()
  const library = page.getByRole('navigation', { name: '引导功能库' })
  await expect(library.getByRole('button')).toHaveCount(7)
  await expect(library.getByRole('button', { name: '添加视频工作流', exact: true })).toBeEnabled()
  await expect(library.getByRole('button', { name: '添加AI 工作助手', exact: true })).toBeEnabled()
  await expect(library.getByRole('button', { name: /喷注器/ })).toHaveCount(0)
  const canvas = page.getByLabel('流程画布', { exact: true })
  await expect(page.getByRole('button', { name: '重置画布缩放', exact: true })).toHaveText('100%')
  await library.getByRole('button', { name: '添加化学平衡分析' }).dragTo(canvas, { targetPosition: { x: 180, y: 160 } })
  const chemistry = page.getByRole('article', { name: '化学平衡分析', exact: true })
  await expect(chemistry).toBeVisible()
  await expect(chemistry.getByRole('button', { name: '打开化学平衡分析' })).toHaveCount(0)
  await page.getByRole('button', { name: '缩小画布' }).click()
  await library.getByRole('button', { name: '添加喷管初步设计' }).dragTo(canvas, { targetPosition: { x: 600, y: 290 } })
  const nozzle = page.getByRole('article', { name: '喷管初步设计', exact: true })
  await expect(nozzle).toBeVisible()
  const canvasBox = (await canvas.boundingBox())!, nozzleBox = (await nozzle.boundingBox())!
  expect(nozzleBox.x - canvasBox.x).toBeCloseTo(600 - 116 * 0.9, 0)
  const heading = nozzle.getByRole('button', { name: '移动喷管初步设计' })
  const before = (await heading.boundingBox())!
  await page.mouse.move(before.x + 70, before.y + 20)
  await page.mouse.down()
  await page.mouse.move(before.x + 160, before.y + 65, { steps: 8 })
  await page.mouse.up()
  const after = (await heading.boundingBox())!
  expect(after.x - before.x).toBeCloseTo(90, 0)
  await heading.press('ArrowDown')
  expect((await heading.boundingBox())!.y - after.y).toBeCloseTo(20 * 0.9, 0)
  await page.getByRole('button', { name: '重置画布缩放', exact: true }).click()
  await expect(page.getByRole('button', { name: '重置画布缩放', exact: true })).toHaveText('100%')
  await chemistry.getByRole('button', { name: '化学平衡分析输出端' }).click()
  await nozzle.getByRole('button', { name: '喷管初步设计输入端' }).click()
  const link = page.getByRole('button', { name: '连接：化学平衡分析 → 喷管初步设计' })
  await expect(link).toHaveCount(1)
  await chemistry.getByRole('button', { name: '化学平衡分析输出端' }).click()
  await nozzle.getByRole('button', { name: '喷管初步设计输入端' }).click()
  await expect(page.getByText('这两个节点已连接', { exact: true })).toBeVisible()
  await link.focus()
  await link.press('Enter')
  await page.getByRole('button', { name: '删除所选连接' }).click()
  await expect(link).toHaveCount(0)
  await chemistry.getByRole('button', { name: '化学平衡分析输出端' }).click()
  await nozzle.getByRole('button', { name: '喷管初步设计输入端' }).click()
  await page.screenshot({ path: test.info().outputPath('guide-connected.png') })
  await nozzle.getByRole('button', { name: '移除喷管初步设计' }).click()
  await expect(link).toHaveCount(0)
  expect(errors).toEqual([])
})

test('opening a workspace and returning preserves the draft; startup always returns to guide', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '添加喷管初步设计' }).click()
  await page.getByRole('button', { name: '添加流体力学' }).click()
  await page.getByRole('button', { name: '喷管初步设计输出端' }).click()
  await page.getByRole('button', { name: '流体力学输入端' }).click()
  await page.getByRole('button', { name: '打开喷管初步设计' }).click()
  await expect(page.getByRole('heading', { name: '喷管初步设计', exact: true })).toBeVisible()
  await selectWorkspace(page, '引导界面')
  await expect(page.getByRole('article')).toHaveCount(2)
  await expect(page.getByRole('button', { name: '连接：喷管初步设计 → 流体力学' })).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('region', { name: '引导界面', exact: true })).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(0)
})

test('search, keyboard connection cancellation and compact layout remain usable', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '搜索功能' }).fill('不存在')
  await expect(page.getByText('没有匹配的功能')).toBeVisible()
  await page.getByRole('textbox', { name: '搜索功能' }).fill('喷管')
  await page.getByRole('button', { name: '添加喷管初步设计' }).press('Enter')
  await page.getByRole('button', { name: '喷管初步设计输出端' }).press('Enter')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '喷管初步设计输出端' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('textbox', { name: '搜索功能' }).fill('')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('textbox', { name: '搜索功能' })).toBeVisible()
  await page.getByRole('button', { name: '添加流体力学' }).click()
  await expect(page.getByRole('article')).toHaveCount(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('guide-compact.png') })
})

test('fixed entries and dynamic workspace tabs support opening, deduplication and closing', async ({ page }) => {
  await page.goto('/')
  const tabs = page.getByRole('tablist', { name: '工作区页签' })
  const start = tabs.getByRole('tab', { name: '开始', exact: true })
  const library = tabs.getByRole('tab', { name: '功能库', exact: true })
  await expect(tabs.getByRole('tab')).toHaveCount(2)
  await expect(tabs.getByRole('button')).toHaveCount(0)
  await library.click()
  await expect(page.getByRole('navigation', { name: '可用功能' }).getByRole('button', { name: '化学平衡分析 未接入', exact: true })).toBeDisabled()
  await expect(page.getByRole('navigation', { name: '可用功能' }).getByRole('button', { name: '视频工作流', exact: true })).toBeEnabled()
  await expect(page.getByRole('navigation', { name: '可用功能' }).getByRole('button', { name: 'AI 工作助手', exact: true })).toBeEnabled()
  await expect(page.getByRole('navigation', { name: '可用功能' }).getByRole('button', { name: /喷注器/ })).toHaveCount(0)
  await selectWorkspace(page, '喷管初步设计')
  const nozzle = tabs.getByRole('tab', { name: '喷管初步设计', exact: true })
  await expect(nozzle).toHaveAttribute('aria-selected', 'true')
  await library.click()
  await page.getByRole('navigation', { name: '可用功能' }).getByRole('button', { name: '喷管初步设计', exact: true }).click()
  await expect(tabs.getByRole('tab')).toHaveCount(3)
  await selectWorkspace(page, '视频工作流')
  const video = tabs.getByRole('tab', { name: '视频工作流', exact: true })
  await expect(tabs.getByRole('tab')).toHaveCount(4)
  await expect(video).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: test.info().outputPath('workspace-tabs.png') })
  await tabs.getByRole('button', { name: '关闭喷管初步设计页签' }).click()
  await expect(video).toHaveAttribute('aria-selected', 'true')
  await expect(video).toBeFocused()
  await selectWorkspace(page, '喷管初步设计')
  await selectWorkspace(page, '钢网设计与制造')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(start).toBeInViewport()
  await expect(library).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await nozzle.click()
  await page.screenshot({ path: test.info().outputPath('workspace-tabs-overflow.png') })
  await nozzle.press('Delete')
  const stencil = tabs.getByRole('tab', { name: '钢网设计与制造', exact: true })
  await expect(stencil).toHaveAttribute('aria-selected', 'true')
  await expect(stencil).toBeFocused()
  await stencil.press('Delete')
  await expect(video).toHaveAttribute('aria-selected', 'true')
  await video.press('Delete')
  await expect(start).toHaveAttribute('aria-selected', 'true')
  await expect(start).toBeFocused()
  await expect(tabs.getByRole('tab')).toHaveCount(2)
  await start.press('ArrowRight')
  await expect(library).toHaveAttribute('aria-selected', 'true')
  await library.press('Delete')
  await expect(library).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('workspace-tabs-compact.png') })
})
